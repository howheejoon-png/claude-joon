/* ------------------------------------------------------------------------
 * Production-class analysis: methods, Spring endpoints, security
 * annotations, decision points, thrown exceptions, null checks, relational
 * boundaries and collaborator side-effects.
 * --------------------------------------------------------------------- */

const SIDE_EFFECT_NAME = /^(save|saveAll|saveAndFlush|insert|update|upsert|delete|deleteById|deleteAll|remove|persist|merge|flush|send|sendEmail|publish|publishEvent|notify|emit|dispatch|post|write|audit|record|execute|submit|enqueue|push|register|evict|invalidate|increment|decrement|transfer|charge|refund|approve|reject|cancel|schedule|store|put|create|log)/;
const NULL_CHECK_CALLS = new Set(['requireNonNull', 'isNull', 'nonNull', 'isEmpty', 'isBlank', 'hasText', 'hasLength', 'isNotBlank', 'isNotEmpty', 'ofNullable', 'requireNonNullElse', 'isPresent']);
const SECURITY_METHOD_ANNS = new Set(['PreAuthorize', 'PostAuthorize', 'Secured', 'RolesAllowed', 'DenyAll', 'PreFilter', 'PostFilter']);
const MAPPING_ANNS = { GetMapping: 'GET', PostMapping: 'POST', PutMapping: 'PUT', DeleteMapping: 'DELETE', PatchMapping: 'PATCH', RequestMapping: 'ANY' };
const LOMBOK_ANNS = new Set(['Data', 'Getter', 'Setter', 'Builder', 'Value', 'AllArgsConstructor', 'NoArgsConstructor', 'RequiredArgsConstructor', 'EqualsAndHashCode', 'ToString', 'SuperBuilder', 'With']);

function analyzeSourceClass(ctx, ty) {
  const { P } = ctx;
  const T = P.T;
  const classMapping = annNamed(ty.anns, 'RequestMapping');
  const prefixes = classMapping ? (annStrings(classMapping, 'value').concat(annStrings(classMapping, 'path'))) : [];
  const classSecurity = ty.anns.filter((a) => SECURITY_METHOD_ANNS.has(a.name)).map((a) => '@' + a.name + (a.args ? '(' + truncate(oneLine(a.args), 60) + ')' : ''));
  const fieldsByName = new Map(ty.fields.map((f) => [f.name, f]));
  const constants = new Map();
  for (const f of ty.fields) {
    const num = /^(?:new\s+BigDecimal\s*\(\s*"?|BigDecimal\.valueOf\s*\(\s*|Integer\.valueOf\s*\(\s*|Long\.valueOf\s*\(\s*)?(-?\d[\d_]*(?:\.\d+)?)[lLdDfF]?"?\s*\)?$/.exec(f.init || '');
    if (num) constants.set(f.name, Number(num[1].replace(/_/g, '')));
  }
  const stereotype = (annNamed(ty.anns, 'RestController', 'Controller', 'Service', 'Repository', 'Component', 'Configuration', 'Entity', 'Embeddable', 'MappedSuperclass', 'Mapper', 'ControllerAdvice', 'RestControllerAdvice') || {}).name || '';
  const lombok = ty.anns.filter((a) => LOMBOK_ANNS.has(a.name)).map((a) => '@' + a.name);

  const out = {
    fqcn: ty.fqcn, simpleName: ty.name, pkg: ty.pkg || '', binaryName: ty.binaryName, kind: ty.kind, snippetId: ctx.snippet.id,
    snippetSeq: ctx.snippet.seq, line: ty.startLine, endLine: ty.endLine, complete: ty.complete && !ctx.incomplete, ext: ty.ext,
    impl: ty.impl, stereotype, lombok, classSecurity, prefixes, methods: [], fields: ty.fields.map((f) => ({ name: f.name, type: simpleNameOf(f.base), anns: f.anns.map((a) => a.name), line: f.nameLine })),
    isInterface: ty.kind === 'interface' || ty.kind === 'annotation', isAbstract: ty.mods.includes('abstract'), outer: ty.outer ? ty.outer.fqcn : '',
    fragment: ty.kind === 'fragment', enumConstants: ty.enumConstants.map((e) => e.name), recordComponents: ty.recordComponents.map((r) => r.name),
  };

  const methods = ty.methods.slice();
  for (const m of methods) out.methods.push(analyzeSourceMethod(ctx, out, ty, m, fieldsByName, constants, prefixes, classSecurity));
  // Records: implicit accessors are callable and show up in JaCoCo.
  for (const rc of ty.recordComponents) {
    if (!out.methods.some((x) => x.name === rc.name && x.params.length === 0)) {
      out.methods.push(syntheticMethod(out, rc.name, 'accessor', ty.nameLine, 'Record component accessor (generated by the compiler)'));
    }
  }
  out.methodsByName = new Map();
  for (const m of out.methods) {
    if (!out.methodsByName.has(m.name)) out.methodsByName.set(m.name, []);
    out.methodsByName.get(m.name).push(m);
  }
  // Intra-class call graph (who calls whom)
  for (const m of out.methods) {
    m.calledBy = [];
  }
  for (const m of out.methods) {
    for (const callee of m.internalCalls) {
      for (const target of out.methodsByName.get(callee) || []) if (target !== m && !target.calledBy.includes(m.name)) target.calledBy.push(m.name);
    }
  }
  return out;
}

function syntheticMethod(cls, name, kind, line, note) {
  return {
    name, display: name + '()', signature: name + '()', kind, visibility: 'public', isStatic: false, isAbstract: false, hasBody: true, synthetic: true, note,
    params: [], returnBase: null, line, endLine: line, decisions: [], throwsTypes: [], nullChecks: [], comparisons: [], collaborators: [], internalCalls: [],
    endpoints: [], security: [], complexity: 1, validationAnns: [], calledBy: [], cls: cls.fqcn,
  };
}

function analyzeSourceMethod(ctx, cls, ty, m, fieldsByName, constants, prefixes, classSecurity) {
  const { P } = ctx;
  const T = P.T;
  const vis = m.mods.includes('public') ? 'public' : m.mods.includes('protected') ? 'protected' : m.mods.includes('private') ? 'private' : (cls.isInterface ? 'public' : 'package');
  const paramsText = m.params.map((p) => p.type + ' ' + p.name).join(', ');
  const kind = classifyMethodKind(m, ty, T);
  const res = {
    name: m.ctor ? '<init>' : m.name, sourceName: m.name, display: (m.ctor ? m.name + ' (constructor)' : m.name) + '(' + m.params.map((p) => simpleNameOf(p.base) + (p.varargs ? '...' : '')).join(', ') + ')',
    signature: (m.returnType ? m.returnType + ' ' : '') + m.name + '(' + paramsText + ')', kind, visibility: vis,
    isStatic: m.mods.includes('static'), isAbstract: !m.hasBody, hasBody: m.hasBody, synthetic: false, params: m.params.map((p) => ({ type: simpleNameOf(p.base), name: p.name, anns: p.anns.map((a) => a.name) })),
    returnBase: m.returnBase ? simpleNameOf(m.returnBase) : null, returnType: m.returnType, line: m.line, nameLine: m.nameLine, endLine: m.endLine,
    decisions: [], throwsTypes: [], nullChecks: [], comparisons: [], collaborators: [], internalCalls: [], endpoints: [], security: [],
    complexity: 1, validationAnns: [], cls: cls.fqcn, complete: m.complete, ctor: m.ctor, anns: m.anns.map((a) => a.name),
  };
  res.security = m.anns.filter((a) => SECURITY_METHOD_ANNS.has(a.name)).map((a) => '@' + a.name + (a.args ? '(' + truncate(oneLine(a.args), 60) + ')' : '')).concat(classSecurity.map((s) => s + ' (class)'));
  for (const p of m.params) {
    for (const a of p.anns) {
      if (!/^(NotNull|NotBlank|NotEmpty|Valid|Validated|Positive|PositiveOrZero|Negative|NegativeOrZero|Min|Max|Size|Pattern|Email|DecimalMin|DecimalMax|Nullable|NonNull|Range|Length)$/.test(a.name)) continue;
      const text = '@' + a.name + (a.args ? '(' + oneLine(a.args) + ')' : '') + ' ' + p.name;
      res.validationAnns.push(text);
      // Bean Validation limits are boundaries just like an if-condition.
      const limits = [];
      if (/^(Min|Max|DecimalMin|DecimalMax)$/.test(a.name)) { const v = /-?\d+(?:\.\d+)?/.exec(a.args || ''); if (v) limits.push(Number(v[0])); }
      if (/^(Size|Length|Range)$/.test(a.name)) for (const mm of (a.args || '').matchAll(/\b(?:min|max)\s*=\s*(-?\d+)/g)) limits.push(Number(mm[1]));
      if (/^(Positive|PositiveOrZero|Negative|NegativeOrZero)$/.test(a.name)) limits.push(0);
      for (const v of limits) res.comparisons.push({ line: a.line, op: '@' + a.name, value: v, text: text, via: a.name });
      if (/^(NotNull|NotBlank|NotEmpty)$/.test(a.name)) res.nullChecks.push({ line: a.line, text });
    }
  }

  // Spring endpoints
  for (const a of m.anns) {
    if (!MAPPING_ANNS[a.name]) continue;
    let verbs = [MAPPING_ANNS[a.name]];
    if (a.name === 'RequestMapping') {
      const mm = a.args.match(/RequestMethod\.(\w+)/g);
      verbs = mm ? mm.map((x) => x.split('.')[1]) : ['ANY'];
    }
    let paths = annStrings(a, 'value').concat(annStrings(a, 'path'));
    if (!paths.length) paths = [''];
    const pre = prefixes.length ? prefixes : [''];
    for (const v of verbs) for (const pr of pre) for (const p of paths) res.endpoints.push({ method: v, path: normalisePath(pr + '/' + p) });
  }

  if (!m.hasBody) return res;
  const b = scanBody(P, m.bodyStart, m.bodyEnd);
  const lineText = (ln) => (P.lines[ln - 1] || '').trim();

  // Decision points
  for (let k = m.bodyStart + 1; k < m.bodyEnd; k++) {
    const t = T[k];
    if (t.t === 'id') {
      if (t.v === 'if' && isOp(T[k + 1], '(')) {
        const close = P.M[k + 1];
        const cond = close > 0 ? oneLine(sliceText(P, k + 2, close - 1)) : '';
        const isElseIf = isIdent(T[k - 1], 'else');
        res.decisions.push({ kind: isElseIf ? 'else if' : 'if', line: t.line, text: (isElseIf ? 'else if (' : 'if (') + truncate(cond, 140) + ')', cond });
        collectComparisons(P, res, k + 2, close - 1, constants, t.line);
      } else if (t.v === 'else' && !isIdent(T[k + 1], 'if')) {
        res.decisions.push({ kind: 'else', line: t.line, text: 'else', cond: '' });
      } else if (t.v === 'switch' && isOp(T[k + 1], '(')) {
        const close = P.M[k + 1];
        const cond = close > 0 ? oneLine(sliceText(P, k + 2, close - 1)) : '';
        const bOpen = close + 1;
        const bClose = isOp(T[bOpen], '{') ? P.M[bOpen] : -1;
        const cases = [];
        let hasDefault = false;
        if (bClose > 0) {
          for (let q = bOpen + 1; q < bClose; q++) {
            const x = T[q];
            if (isOp(x, '{') && P.M[q] > q && !isOp(T[q - 1], '->')) { q = P.M[q]; continue; }
            if (isIdent(x, 'switch') && isOp(T[q + 1], '(')) { const c2 = P.M[q + 1]; const b2 = c2 + 1; if (isOp(T[b2], '{') && P.M[b2] > 0) { q = P.M[b2]; continue; } }
            if (isIdent(x, 'case')) {
              let e = q + 1;
              while (e < bClose && !isOp(T[e], ':') && !isOp(T[e], '->')) e++;
              cases.push(oneLine(sliceText(P, q + 1, e - 1)));
              q = e;
            } else if (isIdent(x, 'default') && (isOp(T[q + 1], ':') || isOp(T[q + 1], '->'))) hasDefault = true;
          }
        }
        res.decisions.push({ kind: 'switch', line: t.line, text: 'switch (' + truncate(cond, 80) + ') — ' + plural(cases.length, 'case') + (hasDefault ? ' + default' : ''), cond, cases, hasDefault });
      } else if (t.v === 'catch' && isOp(T[k + 1], '(')) {
        const close = P.M[k + 1];
        res.decisions.push({ kind: 'catch', line: t.line, text: 'catch (' + oneLine(sliceText(P, k + 2, close - 1)) + ')', cond: '' });
      } else if ((t.v === 'for' || t.v === 'while') && isOp(T[k + 1], '(') && !(t.v === 'while' && isOp(T[k - 1], '}') && isIdent(T[P.M[k - 1] - 1], 'do'))) {
        const close = P.M[k + 1];
        const cond = close > 0 ? oneLine(sliceText(P, k + 2, close - 1)) : '';
        res.decisions.push({ kind: 'loop', line: t.line, text: t.v + ' (' + truncate(cond, 100) + ')', cond });
        if (t.v === 'while') collectComparisons(P, res, k + 2, close - 1, constants, t.line);
      } else if (t.v === 'do' && isOp(T[k + 1], '{')) {
        res.decisions.push({ kind: 'loop', line: t.line, text: 'do … while', cond: '' });
      } else if (t.v === 'throw') {
        let type = '';
        if (isIdent(T[k + 1], 'new') && isIdent(T[k + 2])) type = simpleNameOf(readQualified(P, k + 2).name);
        res.throwsTypes.push({ type: type || '(rethrow)', line: t.line, text: truncate(lineText(t.line), 140) });
      }
    } else if (t.t === 'op') {
      if (t.v === '?' && !isOp(T[k - 1], '<') && !isOp(T[k - 1], ',') && !isIdent(T[k + 1], 'extends') && !isIdent(T[k + 1], 'super') && !isOp(T[k + 1], '>') && !isOp(T[k + 1], ',')) {
        res.decisions.push({ kind: 'ternary', line: t.line, text: truncate(lineText(t.line), 140), cond: '' });
      } else if (t.v === '&&' || t.v === '||') {
        res.decisions.push({ kind: t.v, line: t.line, text: truncate(lineText(t.line), 140), cond: '' });
      } else if ((t.v === '==' || t.v === '!=') && (isIdent(T[k + 1], 'null') || isIdent(T[k - 1], 'null'))) {
        res.nullChecks.push({ line: t.line, text: truncate(lineText(t.line), 140) });
      }
    }
  }
  for (const c of b.calls) {
    if (c.name === 'orElseThrow') {
      const arg = argText(P, c, 0);
      const mm = /new\s+([\w.]+)\s*\(/.exec(arg) || /([\w.]+)::new/.exec(arg);
      res.throwsTypes.push({ type: mm ? simpleNameOf(mm[1]) : 'NoSuchElementException', line: c.line, text: truncate(lineText(c.line), 140) });
      res.decisions.push({ kind: 'optional', line: c.line, text: truncate(lineText(c.line), 140), cond: '' });
    } else if (c.name === 'orElse' || c.name === 'orElseGet' || c.name === 'ifPresent' || c.name === 'ifPresentOrElse') {
      res.decisions.push({ kind: 'optional', line: c.line, text: truncate(lineText(c.line), 140), cond: '' });
    }
    if (NULL_CHECK_CALLS.has(c.name)) res.nullChecks.push({ line: c.line, text: truncate(lineText(c.line), 140) });
    if (c.name === 'compareTo' && c.close > 0) {
      const op = T[c.close + 1];
      if (op && op.t === 'op' && /^(<|>|<=|>=|==|!=)$/.test(op.v)) {
        const arg = argText(P, c, 0);
        const v = numericValueOf(arg, constants);
        if (v != null && Number.isFinite(v)) res.comparisons.push({ line: c.line, op: op.v, value: v, text: truncate(lineText(c.line), 140), via: arg });
      }
    }
    // Collaborator calls on fields
    const r = c.recv;
    if (r.kind === 'name' && (r.qualified.indexOf('.') < 0 || r.thisRef)) {
      const f = fieldsByName.get(r.root);
      if (f && !/^[A-Z_0-9]+$/.test(f.name)) {
        const standalone = isStandaloneCall(P, b, c);
        res.collaborators.push({ field: f.name, type: simpleNameOf(f.base), method: c.name, line: c.line, standalone, sideEffect: standalone && SIDE_EFFECT_NAME.test(c.name), text: truncate(lineText(c.line), 140) });
      }
    }
    if ((r.kind === 'none' || r.kind === 'this') && ty.methods.some((x) => x.name === c.name)) res.internalCalls.push(c.name);
  }
  res.internalCalls = uniq(res.internalCalls);
  const branching = res.decisions.filter((d) => d.kind !== 'else').length;
  res.complexity = 1 + branching + res.decisions.filter((d) => d.kind === 'switch').reduce((n, d) => n + Math.max(0, d.cases.length - 1 + (d.hasDefault ? 1 : 0)), 0);
  return res;
}

// The numeric value of a comparison operand: a literal, a known constant, or
// BigDecimal.ZERO / valueOf(5) / new BigDecimal("10.00"). Null when unknown.
function numericValueOf(arg, constants) {
  const s = String(arg || '').trim();
  if (constants.has(s)) return constants.get(s);
  if (/^-?\d[\d_]*(\.\d+)?[lLdDfF]?$/.test(s)) return Number(s.replace(/[_lLdDfF]/g, ''));
  const named = /BigDecimal\.(ZERO|ONE|TEN)\b/.exec(s);
  if (named) return { ZERO: 0, ONE: 1, TEN: 10 }[named[1]];
  const wrapped = /(?:valueOf|new\s+BigDecimal|new\s+BigInteger)\s*\(\s*"?(-?\d+(?:\.\d+)?)/.exec(s);
  return wrapped ? Number(wrapped[1]) : null;
}

function collectComparisons(P, res, a, b, constants, line) {
  const T = P.T;
  for (let k = a; k <= b; k++) {
    const t = T[k];
    if (!t || t.t !== 'op' || !/^(<|>|<=|>=|==|!=)$/.test(t.v)) continue;
    const left = T[k - 1];
    const right = T[k + 1];
    let v = null;
    let via = '';
    const val = (tok, negTok) => {
      if (!tok) return null;
      if (tok.t === 'num') { const n = Number(tok.v.replace(/[_lLfFdD]/g, '')); return negTok ? -n : n; }
      if (tok.t === 'id' && constants.has(tok.v)) { via = tok.v; return constants.get(tok.v); }
      return null;
    };
    const rNeg = isOp(right, '-') ? T[k + 2] : null;
    v = rNeg ? val(rNeg, true) : val(right, false);
    if (v == null) v = val(left, false);
    if (v == null || !Number.isFinite(v)) continue;
    if ((t.v === '==' || t.v === '!=') && isIdent(T[k + 1], 'null')) continue;
    // compareTo(...) > 0 is collected separately with the real operand
    if (isOp(left, ')') && P.M[k - 1] > 0 && isIdent(T[P.M[k - 1] - 1], 'compareTo')) continue;
    res.comparisons.push({ line: t.line, op: t.v, value: v, text: truncate((P.lines[t.line - 1] || '').trim(), 140), via });
  }
}

function isStandaloneCall(P, b, c) {
  // Result unused: the chain this call ends is a whole statement.
  let last = c;
  let guard = 0;
  while (last.chainNext.length && guard++ < 30) last = last.chainNext[last.chainNext.length - 1];
  if (last !== c) return false;
  const after = P.T[c.close + 1];
  if (!after || !isOp(after, ';')) return false;
  const startIdx = c.chainRoot.recv.rootIdx != null ? c.chainRoot.recv.rootIdx : c.chainRoot.idx;
  const before = P.T[startIdx - 1];
  return !!before && (isOp(before, ';') || isOp(before, '{') || isOp(before, '}') || isOp(before, '->') || isIdent(before, 'else') || (isOp(before, ')') && false));
}

function classifyMethodKind(m, ty, T) {
  if (m.ctor) return 'constructor';
  const n = m.name;
  if (n === 'main' && m.mods.includes('static')) return 'entry';
  if (/^(equals|hashCode|toString|compareTo|clone)$/.test(n)) return 'object';
  const bodyLen = m.hasBody ? m.bodyEnd - m.bodyStart : 0;
  if (/^(get|is|has)[A-Z]/.test(n) && m.params.length === 0 && bodyLen <= 8) return 'accessor';
  if (/^set[A-Z]/.test(n) && m.params.length === 1 && bodyLen <= 10) return 'accessor';
  if (m.hasBody && T) {
    const body = T.slice(m.bodyStart + 1, m.bodyEnd).map((t) => t.v).join(' ');
    // return name;  /  return this.name;  /  this.name = name;
    if (m.params.length === 0 && /^return (this \. )?[\w$]+ ;$/.test(body)) return 'accessor';
    if (m.params.length === 1 && /^(this \. )?[\w$]+ = [\w$]+ ;$/.test(body)) return 'accessor';
  }
  if (ty.kind === 'record' && m.params.length === 0 && ty.recordComponents.some((r) => r.name === n)) return 'accessor';
  if (/^(builder|build|with[A-Z]\w*)$/.test(n) && bodyLen <= 12) return 'builder';
  return 'logic';
}

/* Index of production classes, resolvable by simple name or FQCN, honouring
 * the importing unit's imports and package when names are ambiguous. */
function buildProductionIndex(classes) {
  const byFqcn = new Map();
  const bySimple = new Map();
  for (const c of classes) {
    byFqcn.set(c.fqcn, c);
    const key = c.simpleName;
    if (!bySimple.has(key)) bySimple.set(key, []);
    bySimple.get(key).push(c);
  }
  // Implementations of interfaces / subclasses
  const implementors = new Map();
  for (const c of classes) {
    for (const parent of c.impl.concat(c.ext)) {
      if (!implementors.has(parent)) implementors.set(parent, []);
      implementors.get(parent).push(c);
    }
  }
  function resolve(name, unit) {
    if (!name) return null;
    if (byFqcn.has(name)) return byFqcn.get(name);
    const simple = simpleNameOf(name);
    const list = bySimple.get(simple);
    if (!list || !list.length) return null;
    if (list.length === 1) return list[0];
    if (unit) {
      const imp = unit.imports.find((i) => !i.isStatic && simpleNameOf(i.name) === simple);
      if (imp && byFqcn.has(imp.name)) return byFqcn.get(imp.name);
      const samePkg = list.find((c) => c.pkg === (unit.pkg || ''));
      if (samePkg) return samePkg;
      const wildcard = unit.imports.filter((i) => !i.isStatic && i.name.endsWith('.*')).map((i) => i.name.slice(0, -2));
      const wc = list.find((c) => wildcard.includes(c.pkg));
      if (wc) return wc;
    }
    return list[list.length - 1];
  }
  return { byFqcn, bySimple, implementors, resolve, classes };
}
